# Email (Gmail) + alertes Telegram
# Les secrets sont lus dans le fichier .env (jamais ecrits ici).
#
# Remarque Django 6.1 : la configuration e-mail se fait avec MAILERS.
# Les anciens reglages du TP (EMAIL_BACKEND, EMAIL_HOST, EMAIL_PORT,
# EMAIL_USE_TLS, EMAIL_HOST_USER, EMAIL_HOST_PASSWORD) sont interdits
# quand MAILERS existe. On met donc EXACTEMENT les memes valeurs ici :
#   EMAIL_BACKEND = smtp          -> "BACKEND"
#   EMAIL_HOST    = smtp.gmail.com -> "host"
#   EMAIL_PORT    = 587            -> "port"
#   EMAIL_USE_TLS = True           -> "use_tls"
#   EMAIL_HOST_USER / PASSWORD     -> "username" / "password"

gmail_user = os.getenv("EMAIL_HOST_USER", "").strip()
# Google affiche le mot de passe d'application avec des espaces : on les retire
gmail_password = os.getenv("EMAIL_HOST_PASSWORD", "").replace(" ", "")

MAILERS = {
    "default": {
        "BACKEND": "django.core.mail.backends.smtp.EmailBackend",
        "OPTIONS": {
            "host": "smtp.gmail.com",
            "port": 587,
            "use_tls": True,
            "username": gmail_user,
            "password": gmail_password,
            "timeout": 10,  # secondes : on ne bloque pas l'ESP trop longtemps
        },
    },
}
DEFAULT_FROM_EMAIL = gmail_user or "webmaster@localhost"

# Destinataire de l'e-mail d'alerte
